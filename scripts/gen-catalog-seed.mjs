#!/usr/bin/env node
// Generates supabase/migrations/20261017000100_catalog_seed.sql: the four templates, the
// four starting books, their bundled content as edition 0, and the starting shelves.
// Deterministic: the same inputs always produce the same file.
//
//   npm run db:seed-catalog

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const OUT = `${ROOT}supabase/migrations/20261017000100_catalog_seed.sql`
const read = (p) => JSON.parse(readFileSync(`${ROOT}${p}`, 'utf8'))

const ALL = { focus: true, listen: true, plans: true, scripture: true, verse_popups: true, notes: true, pen: true, search: true, share: true, journal: true }
const only = (...on) => Object.fromEntries(Object.keys(ALL).map((k) => [k, on.includes(k)]))
const level = (name, show_titles = true) => ({ name, show_titles })

const CONFIG = {
  prayer_manual: { reader: 'prayer', levels: [level('Part'), level('Section')], content: ['prayer', 'foundation'], check_on: 'item', numbering: 'nested', actions_on: 'level-2', schedule: 'fixed', features: ALL },
  watch_manual: { reader: 'prayer', levels: [level('Watch'), level('Topic', false)], content: ['prayer', 'names', 'embed'], check_on: 'item', numbering: 'running', actions_on: 'level-1', schedule: 'fixed', features: ALL },
  weekly_series: { reader: 'prayer', levels: [level('Week')], content: ['prayer'], check_on: 'item', numbering: 'nested', actions_on: 'level-1', schedule: 'dated', features: only('focus', 'listen', 'share') },
  devotional: { reader: 'reading', levels: [level('Chapter')], content: ['reading'], check_on: 'none', numbering: 'none', actions_on: 'level-1', schedule: 'fixed', features: only('listen', 'verse_popups', 'notes', 'pen', 'search') },
}
const TEMPLATES = [
  ['prayer_manual', 'Prayer manual', 'Parts and sections of numbered prayers with scripture, checked off one by one (like the Book of Covenant Prayers).'],
  ['watch_manual', 'Watch manual', 'Prayer watches with prayers numbered through each watch, plus name lists (like Jesus Chosen Fast and Prayer).'],
  ['devotional', 'Devotional', 'Chapters of reading with highlights and notes (like Rooted).'],
  ['weekly_series', 'Weekly series', 'Dated entries published over time, newest first (like the Weekly Kingdom Prayers).'],
]

const rooted = read('site/books/rooted.json')
const BOOKS = [
  { slug: 'covenant', template: 'prayer_manual', title: 'Book of Covenant Prayers', subtitle: '', author: '', access: 'members', sort: 1, cover: { colors: ['#25685d', '#11372f', '#d9c27e'] }, content: read('site/prayers.json') },
  { slug: 'jcfp', template: 'watch_manual', title: 'Jesus Chosen Fast and Prayer Prayer Manual', subtitle: '', author: '', access: 'free', sort: 2, cover: { colors: ['#8e2d3a', '#561620', '#dcb86c'] }, content: read('site/jcfp.json') },
  { slug: 'weekly', template: 'weekly_series', title: 'GRA Weekly Kingdom Prayers', subtitle: '', author: '', access: 'free', sort: 0, cover: { colors: ['#33407a', '#171d40', '#e6c47a'] }, content: null },
  { slug: 'rooted', template: 'devotional', title: rooted.title, subtitle: rooted.subtitle || '', author: rooted.author || '', access: 'free', sort: 10, cover: rooted.cover || {}, content: rooted },
]

const SECTIONS = [
  ['home', 'this_week', 'GRA Weekly Kingdom Prayers', 1, []],
  ['home', 'plan', 'Today’s Plan', 2, []],
  ['home', 'continue', 'Continue', 3, []],
  ['home', 'shelf', 'My Prayer Library', 4, ['covenant', 'jcfp', 'weekly']],
  ['home', 'shelf', 'Spiritual Nourishment', 5, ['rooted']],
  ['store', 'shelf', 'Prayer books', 1, ['covenant', 'jcfp']],
  ['store', 'shelf', 'Spiritual Nourishment', 2, ['rooted']],
]

// Same as layoutOf() in app/src/features/book/layout.ts: stable ids for every part,
// section and prayer, so progress follows prayers across editions.
function layoutOf(data) {
  return data.map((p, pi) => ({
    u: p.u || `part-${pi + 1}`,
    s: p.sections.map((s, si) => ({ u: s.u || `s-${pi + 1}-${si + 1}`, p: s.prayers.map((pr, i) => pr.u || `s-${pi + 1}-${si + 1}-${i + 1}`) })),
  }))
}

const q = (s) => `'${String(s).replace(/'/g, "''")}'`
const j = (v) => {
  const s = JSON.stringify(v)
  if (s.includes('$json$')) throw new Error('content contains the $json$ quote marker')
  return `$json$${s}$json$::jsonb`
}
// Stable section ids so re-running the seed never duplicates shelves.
const sectionId = (i) => `00000000-0000-4000-8000-${String(i + 1).padStart(12, '0')}`

const sql = [
  '-- GENERATED by scripts/gen-catalog-seed.mjs — do not edit by hand.',
  '-- Starting catalog: templates, the four books, their bundled content as edition 0, shelves.',
  '',
  ...TEMPLATES.map(([key, name, desc]) => `insert into public.book_templates (key, name, description, config) values (${q(key)}, ${q(name)}, ${q(desc)}, ${j(CONFIG[key])}) on conflict (key) do nothing;`),
  '',
  ...BOOKS.map(
    (b) =>
      `insert into public.books (slug, template, config, title, subtitle, author, cover, access, status, sort_hint) values (${q(b.slug)}, ${q(b.template)}, ${j(CONFIG[b.template])}, ${q(b.title)}, ${q(b.subtitle)}, ${q(b.author)}, ${j(b.cover)}, ${q(b.access)}, 'published', ${b.sort}) on conflict (slug) do nothing;`,
  ),
  '',
  ...BOOKS.filter((b) => b.content).map(
    (b) =>
      `insert into public.book_editions (book_slug, version, data, layout, note) values (${q(b.slug)}, 0, ${j(b.content)}, ${j(b.template === 'devotional' ? [] : layoutOf(b.content))}, 'Bundled edition') on conflict (book_slug, version) do nothing;`,
  ),
  '',
  ...SECTIONS.flatMap(([placement, kind, title, position, books], i) => [
    `insert into public.sections (id, placement, kind, title, position) values ('${sectionId(i)}', ${q(placement)}, ${q(kind)}, ${q(title)}, ${position}) on conflict (id) do nothing;`,
    ...books.map((slug, k) => `insert into public.section_books (section_id, book_slug, position) values ('${sectionId(i)}', ${q(slug)}, ${k + 1}) on conflict do nothing;`),
  ]),
  '',
].join('\n')

writeFileSync(OUT, sql)
console.log(`wrote ${OUT.replace(ROOT, '')} (${(sql.length / 1024).toFixed(0)} KB)`)
